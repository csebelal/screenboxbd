export function getAllPosts(): BlogPost[] {
  return BLOG_POSTS;
}

export function getFeaturedPost(): BlogPost {
  return BLOG_POSTS.find((p) => p.featured) || BLOG_POSTS[0];
}

export function getPostBySlug(slug: string): BlogPost | undefined {
  return BLOG_POSTS.find((p) => p.slug === slug);
}

export function getRelatedPosts(currentSlug: string, limit: number = 3): BlogPost[] {
  const currentPost = getPostBySlug(currentSlug);
  if (!currentPost) return BLOG_POSTS.slice(0, limit);

  return BLOG_POSTS.filter(
    (p) => p.slug !== currentSlug && (p.categorySlug === currentPost.categorySlug || p.tags.some((t) => currentPost.tags.includes(t)))
  ).slice(0, limit);
}

export function getPostsByCategory(categorySlug: string): BlogPost[] {
  if (categorySlug === "all") return BLOG_POSTS;
  return BLOG_POSTS.filter((p) => p.categorySlug === categorySlug);
}

export function getBlogCategories(): BlogCategory[] {
  return BLOG_CATEGORIES;
}
